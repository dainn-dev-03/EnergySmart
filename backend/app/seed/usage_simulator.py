"""Deterministic hourly electricity simulator for the demo data.

Every (meter, day) pair has its own random stream, so a day always produces the same readings
whether it is generated by a full seed or later by a top-up run.
"""

import math
import random
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from datetime import date, datetime, time, timedelta
from decimal import Decimal
from typing import Any

from app.core.enums import MeterStatus
from app.core.timezone import APP_TIMEZONE
from app.services.electricity_usage_service import calculate_cost

HOURS_PER_DAY = 24
# Outdoor temperature drives air-conditioning: Hanoi peaks mid-July (day-of-year ~196).
_SEASON_PEAK_DAY_OF_YEAR = 196
_SEASON_AMPLITUDE = 0.4
_NIGHT_HOURS = frozenset((*range(0, 7), *range(19, 24)))


@dataclass(frozen=True)
class LoadProfile:
    """Share of a room's peak load per hour of a weekday, plus weekend/seasonal behaviour."""

    name: str
    hourly: tuple[float, ...]
    saturday: float
    sunday: float
    # Fraction of the load that follows outdoor temperature (air-conditioning).
    seasonal_sensitivity: float

    def __post_init__(self) -> None:
        if len(self.hourly) != HOURS_PER_DAY:
            raise ValueError(f"Profile {self.name} must have {HOURS_PER_DAY} hourly values")

    @property
    def weekday_peak_hours(self) -> float:
        """Energy of a normal weekday expressed in hours at peak load."""
        return sum(self.hourly)


def _hours(*segments: tuple[int, float]) -> tuple[float, ...]:
    """Build 24 hourly values from (number_of_hours, value) segments."""
    values = tuple(value for count, value in segments for _ in range(count))
    if len(values) != HOURS_PER_DAY:
        raise ValueError("Segments must cover exactly 24 hours")
    return values


